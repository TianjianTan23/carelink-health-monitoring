    def test_stale_data_and_rotated_logged_out_tokens(self):
        b=self.body();self.client.post('/sensor-data',content=b,headers=self.headers(b));self.login();old=self.client.cookies.get('carelink_session')
        headers={'Origin':'https://testserver','X-CareLink-CSRF':'1'}
