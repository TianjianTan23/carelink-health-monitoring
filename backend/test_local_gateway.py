    def test_actual_field_shape_null_held_pulse_still_uploads_and_maps_to_ttj(self):
        # Synthetic copy of the reported SHAPE only; never sent to live gateway.
        b=self.body(heart_rate_bpm=None,heart_rate_ok=False,
                    heart_rate_display_bpm=93.6,heart_rate_held=True,
                    heart_rate_error='STABILIZING: first pulse detected',
                    ambient_temp_c=27.63,object_temp_c=26.15,
                    accel_x_g=-0.4,accel_y_g=-0.15,accel_z_g=0.81,accel_total_g=0.92)
        h=self.headers(b)
        with self.assertLogs('carelink.device',level='INFO') as captured:
            response=self.client.post('/sensor-data',content=b,headers=h)
        self.assertEqual(response.status_code,200);self.assertEqual(self.count(),1)
        messages='\n'.join(captured.output)
        stages=['request_received','hmac_timestamp_verified','nonce_reserved','readings_committed','http_complete status=200']
        self.assertEqual(sorted(messages.index(stage) for stage in stages),[messages.index(stage) for stage in stages])
        for secret in [self.api,self.key.hex(),h['X-CareLink-Nonce'],h['X-CareLink-Signature'],b.decode()]:self.assertNotIn(secret,messages)
        self.login();reading=self.client.get('/api/patients/ttj').json()['reading']
        self.assertEqual(reading['patientId'],'ttj');self.assertEqual(reading['deviceId'],self.device)
        self.assertIsNone(reading['metrics']['hr']['value']);self.assertEqual(reading['metrics']['temp']['value'],26.15)
        self.assertNotIn('spo2',reading['metrics']);self.assertTrue(reading['connected'])
        self.assertEqual(reading['source'],'device');self.assertEqual(response.json()['received_at'],reading['receivedAt'])
        with self.assertLogs('carelink.device',level='INFO') as captured:
            replay=self.client.post('/sensor-data',content=b,headers=h)
        self.assertEqual(replay.status_code,409);self.assertEqual(self.count(),1)
        self.assertNotIn('stage=nonce_reserved','\n'.join(captured.output));self.assertNotIn('stage=readings_committed','\n'.join(captured.output))

    def test_failed_auth_has_safe_diagnostics_and_no_business_operations(self):
        b=self.body();h=self.headers(b);h['X-CareLink-Signature']='f'*64
        with self.assertLogs('carelink.device',level='INFO') as captured:
            result=self.client.post('/sensor-data',content=b,headers=h)
        self.assertEqual(result.status_code,401);self.assertEqual(self.count(),0)
        messages='\n'.join(captured.output)
        self.assertIn('stage=authentication_rejected status=401',messages)
        for forbidden in [self.api,self.key.hex(),h['X-CareLink-Signature'],h['X-CareLink-Nonce'],b.decode(),'stage=nonce_reserved','stage=readings_committed']:self.assertNotIn(forbidden,messages)
    def test_forgery_expiration_replay_have_no_extra_rows(self):
        b=self.body();h=self.headers(b);self.assertEqual(self.client.post('/sensor-data',content=b,headers=h).status_code,200)
        self.assertEqual(self.client.post('/sensor-data',content=b,headers=h).status_code,409)
        for key,value in [('X-CareLink-Api-Key','A'*43),('X-CareLink-Signature','0'*64)]:
            bad=self.headers(b);bad[key]=value;self.assertEqual(self.client.post('/sensor-data',content=b,headers=bad).status_code,401)
        self.assertEqual(self.client.post('/sensor-data',content=b,headers=self.headers(b,int(time.time())-120)).status_code,401)
        self.assertEqual(self.client.post('/sensor-data',content=b,headers={'Content-Type':'application/json'}).status_code,401);self.assertEqual(self.count(),1)
