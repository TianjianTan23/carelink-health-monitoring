class LocalGatewayTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory(prefix='carelink-integration-');self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)/'gateway';self.device='integration-software-fixture'
        # Public, synthetic account only. Original passwords/databases never read.
        with socket.socket() as probe:probe.bind(('127.0.0.1',0));port=probe.getsockname()[1]
        self.cfg=create_new(self.root,{'fixture-clinician':{'password_hash':hash_password('synthetic-integration-password'),'role':'clinician','mode':'pro','patient_ids':['ttj'],'needs_password_rotation':0}},device_id=self.device,port=port)
        self.env=patch.dict(os.environ,self.cfg['environment']);self.env.start();self.addCleanup(self.env.stop)
        core=importlib.import_module('backend.app');self.old_path=core.DATABASE_PATH;self.old_routes=list(core.app.router.routes)
        self.addCleanup(setattr,core,'DATABASE_PATH',self.old_path);self.addCleanup(setattr,core.app.router,'routes',self.old_routes)
        self.cfg['environment']['CARELINK_WEB_ORIGINS']='https://testserver'
        os.environ['CARELINK_WEB_ORIGINS']='https://testserver'
        self.client=TestClient(app_from_config(self.cfg),base_url='https://testserver');self.client.__enter__();self.addCleanup(self.client.__exit__,None,None,None)
        # Private fixture header is read in memory and never printed.
        header=(self.root/'firmware/elder_sensors/device_auth.h').read_text()
        import re
        self.api=re.search(r'DEVICE_API_KEY\[\] = "([^"]+)"',header).group(1)
        self.key=bytes.fromhex(re.search(r'DEVICE_HMAC_KEY_HEX\[\] = "([^"]+)"',header).group(1))
    def body(self,**more):
        return json.dumps({'device_id':self.device,'patient_id':'patient-01','heart_rate_bpm':76,'heart_rate_ok':True,'object_temp_c':36.7,'mlx90614_ok':True,'mpu6050_ok':True,'fall_detected':False,**more},separators=(',',':')).encode()
    def headers(self,body,stamp=None,nonce=None):
        stamp=str(int(time.time()) if stamp is None else stamp);nonce=nonce or secrets.token_hex(16)
        canonical='\n'.join(['CARELINK-HMAC-SHA256-V1','POST','/sensor-data',self.device,stamp,nonce,hashlib.sha256(body).hexdigest()]).encode()
        return {'Content-Type':'application/json','X-CareLink-Device-Id':self.device,'X-CareLink-Api-Key':self.api,'X-CareLink-Timestamp':stamp,'X-CareLink-Nonce':nonce,'X-CareLink-Signature':hmac.new(self.key,canonical,hashlib.sha256).hexdigest()}
    def login(self,client=None):
        client=client or self.client
        response=client.post('/api/login',headers={'Origin':'https://testserver','X-CareLink-CSRF':'1'},json={'username':'fixture-clinician','password':'synthetic-integration-password'})
        self.assertEqual(response.status_code,200)
    def count(self):
        with closing(sqlite3.connect(self.cfg['environment']['CARELINK_DATABASE_PATH'])) as db:return db.execute('SELECT count(*) FROM readings').fetchone()[0]
